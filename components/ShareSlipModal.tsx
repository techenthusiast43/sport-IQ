'use client';

import React, { useState, useRef } from 'react';
import {
  X,
  Share2,
  Copy,
  Check,
  Download,
  ShieldCheck,
  Zap,
  TrendingUp,
  MessageCircle,
  Sparkles,
} from 'lucide-react';
import { BetLeg, BookmakerId } from '@/lib/types';
import { BOOKMAKERS } from '@/lib/mockData';
import { getSurvivalTier } from '@/lib/survivalScore';

interface ShareSlipModalProps {
  isOpen: boolean;
  targetBookmaker: BookmakerId;
  targetBookingCode: string;
  legs: BetLeg[];
  totalOdds: number;
  stake: number;
  survivalScore: number;
  isOfficialCode?: boolean;
  onClose: () => void;
}

export const ShareSlipModal: React.FC<ShareSlipModalProps> = ({
  isOpen,
  targetBookmaker,
  targetBookingCode,
  legs,
  totalOdds,
  stake,
  survivalScore,
  isOfficialCode = false,
  onClose,
}) => {
  const [copiedText, setCopiedText] = useState(false);
  const [isDownloading, setIsDownloading] = useState(false);
  const cardRef = useRef<HTMLDivElement>(null);

  if (!isOpen) return null;

  const targetBm = BOOKMAKERS.find((b) => b.id === targetBookmaker) || BOOKMAKERS[1];
  const tier = getSurvivalTier(survivalScore);
  const totalPayout = totalOdds * stake;

  // Format WhatsApp / Telegram clean message
  const handleCopyChatFormat = () => {
    const lines = [
      `🚀 *SPORTIQ VERIFIED BET SLIP*`,
      `🎯 Bookmaker: *${targetBm.name}*`,
      `🔑 Booking Code: *${targetBookingCode || '------'}*${isOfficialCode && targetBookmaker === 'SportyBet' ? ' *(Official SportyBet Code - Verified)*' : ''}`,
      `📈 Total Odds: *${totalOdds.toFixed(2)}* | AI Survival: *${survivalScore}%* (${tier.label})`,
      `💰 Stake: ₦${stake.toLocaleString()} | Est. Payout: *₦${Math.round(totalPayout).toLocaleString()}*`,
      `─────────────────────────`,
    ];

    legs.forEach((l, idx) => {
      lines.push(`${idx + 1}. ⚽ *${l.homeTeam} vs ${l.awayTeam}* (${l.league})`);
      lines.push(`   👉 Pick: *${l.targetSelection || l.selection}* @ *${l.odds.toFixed(2)}* [${l.riskLevel}]`);
    });

    lines.push(`─────────────────────────`);
    lines.push(`⚡ Generated by SportIQ AI Code Bridge`);

    navigator.clipboard.writeText(lines.join('\n'));
    setCopiedText(true);
    setTimeout(() => setCopiedText(false), 2400);
  };

  // Canvas Image Generator for clean PNG download without external dependencies
  const handleDownloadImage = () => {
    setIsDownloading(true);

    const canvas = document.createElement('canvas');
    const width = 800;
    const height = Math.max(900, 420 + legs.length * 80);
    canvas.width = width;
    canvas.height = height;

    const ctx = canvas.getContext('2d');
    if (!ctx) {
      setIsDownloading(false);
      return;
    }

    // 1. Background gradient
    const bgGrad = ctx.createLinearGradient(0, 0, 0, height);
    bgGrad.addColorStop(0, '#020617'); // slate-950
    bgGrad.addColorStop(1, '#090d16');
    ctx.fillStyle = bgGrad;
    ctx.fillRect(0, 0, width, height);

    // Subtle border
    ctx.strokeStyle = '#1e293b';
    ctx.lineWidth = 4;
    ctx.strokeRect(10, 10, width - 20, height - 20);

    // Accent line at top
    const lineGrad = ctx.createLinearGradient(40, 20, width - 40, 20);
    lineGrad.addColorStop(0, '#10b981');
    lineGrad.addColorStop(0.5, '#06b6d4');
    lineGrad.addColorStop(1, '#3b82f6');
    ctx.fillStyle = lineGrad;
    ctx.fillRect(40, 24, width - 80, 4);

    // Brand title
    ctx.font = 'bold 30px sans-serif';
    ctx.fillStyle = '#ffffff';
    ctx.fillText('SportIQ', 44, 70);

    ctx.font = '14px monospace';
    ctx.fillStyle = '#34d399';
    ctx.fillText('VERIFIED BET SLIP • FREE v2.5', 44, 94);

    // Target bookmaker badge
    ctx.fillStyle = '#0f172a';
    ctx.fillRect(width - 240, 45, 196, 50);
    ctx.strokeStyle = '#334155';
    ctx.lineWidth = 1.5;
    ctx.strokeRect(width - 240, 45, 196, 50);

    ctx.font = 'bold 16px sans-serif';
    ctx.fillStyle = '#22d3ee';
    ctx.fillText(targetBm.name, width - 220, 76);

    // Booking Code Banner
    ctx.fillStyle = '#061b17';
    ctx.fillRect(40, 120, width - 80, 100);
    ctx.strokeStyle = '#059669';
    ctx.lineWidth = 2;
    ctx.strokeRect(40, 120, width - 80, 100);

    ctx.font = '13px sans-serif';
    ctx.fillStyle = '#6ee7b7';
    ctx.fillText(`TARGET BOOKING CODE (${targetBm.name})`, 60, 150);

    ctx.font = 'bold 36px monospace';
    ctx.fillStyle = '#34d399';
    ctx.fillText(targetBookingCode || '------', 60, 195);

    // Stats bar: Odds & Survival Score
    ctx.fillStyle = '#0f172a';
    ctx.fillRect(40, 235, width - 80, 75);
    ctx.strokeStyle = '#1e293b';
    ctx.lineWidth = 1;
    ctx.strokeRect(40, 235, width - 80, 75);

    ctx.font = '12px sans-serif';
    ctx.fillStyle = '#94a3b8';
    ctx.fillText('TOTAL ODDS', 60, 260);
    ctx.font = 'bold 24px monospace';
    ctx.fillStyle = '#22d3ee';
    ctx.fillText(totalOdds.toFixed(2), 60, 290);

    ctx.font = '12px sans-serif';
    ctx.fillStyle = '#94a3b8';
    ctx.fillText('AI SURVIVAL SCORE', 250, 260);
    ctx.font = 'bold 24px monospace';
    ctx.fillStyle = '#34d399';
    ctx.fillText(`${survivalScore}% (${tier.label})`, 250, 290);

    ctx.font = '12px sans-serif';
    ctx.fillStyle = '#94a3b8';
    ctx.fillText('EST. PAYOUT', 520, 260);
    ctx.font = 'bold 22px monospace';
    ctx.fillStyle = '#f8fafc';
    ctx.fillText(`₦${Math.round(totalPayout).toLocaleString()}`, 520, 290);

    // Matches List
    let y = 350;
    ctx.font = 'bold 15px sans-serif';
    ctx.fillStyle = '#e2e8f0';
    ctx.fillText(`Selections (${legs.length} matches):`, 40, y);
    y += 25;

    legs.forEach((leg, index) => {
      // Leg background container
      ctx.fillStyle = '#0b1120';
      ctx.fillRect(40, y, width - 80, 64);
      ctx.strokeStyle = '#1e293b';
      ctx.strokeRect(40, y, width - 80, 64);

      // Match info
      ctx.font = 'bold 14px sans-serif';
      ctx.fillStyle = '#ffffff';
      ctx.fillText(`${index + 1}. ${leg.homeTeam} vs ${leg.awayTeam}`, 55, y + 25);

      ctx.font = '11px sans-serif';
      ctx.fillStyle = '#64748b';
      ctx.fillText(leg.league, 55, y + 45);

      // Pick & Odds
      ctx.font = 'bold 13px sans-serif';
      ctx.fillStyle = '#38bdf8';
      ctx.fillText(`Pick: ${leg.targetSelection || leg.selection}`, 440, y + 25);

      ctx.font = 'bold 14px monospace';
      ctx.fillStyle = '#34d399';
      ctx.fillText(`@ ${leg.odds.toFixed(2)}`, 680, y + 25);

      y += 76;
    });

    // Watermark footer
    y += 15;
    ctx.font = '12px sans-serif';
    ctx.fillStyle = '#475569';
    ctx.fillText('Generated by SportIQ AI Engine • Please Gamble Responsibly (18+)', 40, y);

    // Export to download link
    const dataUrl = canvas.toDataURL('image/png');
    const a = document.createElement('a');
    a.href = dataUrl;
    a.download = `SportIQ-Slip-${targetBookingCode || 'Ticket'}.png`;
    a.click();

    setIsDownloading(false);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 sm:p-6 overflow-y-auto">
      {/* Backdrop */}
      <div
        className="fixed inset-0 bg-slate-950/85 backdrop-blur-md transition-opacity"
        onClick={onClose}
      />

      {/* Modal Dialog */}
      <div className="relative z-10 w-full max-w-2xl rounded-2xl border border-slate-800 bg-slate-950 p-6 shadow-2xl my-8">
        {/* Header */}
        <div className="flex items-center justify-between border-b border-slate-800 pb-4">
          <div className="flex items-center gap-2.5">
            <div className="flex h-9 w-9 items-center justify-center rounded-xl bg-gradient-to-tr from-emerald-500/20 to-cyan-500/20 border border-emerald-500/30 text-emerald-400">
              <Share2 className="h-5 w-5" />
            </div>
            <div>
              <h3 className="text-lg font-bold text-white flex items-center gap-2">
                Shareable Slip Receipt
                <span className="rounded-full bg-emerald-500/10 border border-emerald-500/30 px-2 py-0.5 text-[10px] font-medium text-emerald-400">
                  AI Verified
                </span>
              </h3>
              <p className="text-xs text-slate-400">
                Optimized parlay card ready for WhatsApp, Telegram, or image export
              </p>
            </div>
          </div>

          <button
            type="button"
            onClick={onClose}
            className="rounded-lg p-1.5 text-slate-400 hover:bg-slate-800 hover:text-white transition-colors"
          >
            <X className="h-5 w-5" />
          </button>
        </div>

        {/* The Receipt Slip Card */}
        <div
          ref={cardRef}
          className="mt-4 rounded-xl border border-slate-800/90 bg-gradient-to-b from-slate-900 via-slate-900/90 to-slate-950 p-5 shadow-inner"
        >
          {/* Card Top Banner */}
          <div className="flex items-center justify-between border-b border-slate-800/80 pb-3">
            <div className="flex items-center gap-2">
              <Zap className="h-4 w-4 text-emerald-400" />
              <span className="text-sm font-bold tracking-tight text-white">
                SportIQ <span className="text-cyan-400 font-mono text-xs">VERIFIED</span>
              </span>
            </div>

            <div className={`flex items-center gap-1.5 rounded-lg border px-2.5 py-0.5 text-xs font-semibold ${targetBm.badgeColor}`}>
              <span className="h-2 w-2 rounded-full bg-current"></span>
              <span>{targetBm.name}</span>
            </div>
          </div>

          {/* Code Highlight Box */}
          <div className="mt-4 rounded-xl border border-emerald-500/30 bg-emerald-950/20 p-4 text-center">
            <span className="text-[11px] font-mono uppercase tracking-wider text-emerald-400/80 block mb-1">
              Destination Booking Code ({targetBm.name})
            </span>
            <div className="font-mono text-3xl sm:text-4xl font-extrabold tracking-widest text-emerald-300 select-all">
              {targetBookingCode || '------'}
            </div>
            {isOfficialCode && targetBookmaker === 'SportyBet' && (
              <span className="inline-block mt-2 rounded-full bg-emerald-500/20 border border-emerald-500/40 px-2.5 py-0.5 text-[10px] font-semibold text-emerald-300">
                Official SportyBet Code (Verified)
              </span>
            )}
          </div>

          {/* Quick Metrics */}
          <div className="mt-4 grid grid-cols-3 gap-2 text-center">
            <div className="rounded-lg bg-slate-950 p-2.5 border border-slate-800">
              <span className="text-[10px] text-slate-500 uppercase block">Total Odds</span>
              <span className="font-mono font-bold text-cyan-400 text-base">
                {totalOdds.toFixed(2)}
              </span>
            </div>

            <div className="rounded-lg bg-slate-950 p-2.5 border border-slate-800">
              <span className="text-[10px] text-slate-500 uppercase block">Survival Score</span>
              <span className="font-mono font-bold text-emerald-400 text-base">
                {survivalScore}%
              </span>
            </div>

            <div className="rounded-lg bg-slate-950 p-2.5 border border-slate-800">
              <span className="text-[10px] text-slate-500 uppercase block">Est. Payout</span>
              <span className="font-mono font-bold text-white text-base">
                ₦{Math.round(totalPayout).toLocaleString()}
              </span>
            </div>
          </div>

          {/* Match Legs List */}
          <div className="mt-4 max-h-56 overflow-y-auto space-y-2 pr-1 text-xs">
            {legs.map((leg, idx) => (
              <div
                key={leg.id}
                className="flex items-center justify-between rounded-lg bg-slate-950/80 p-2.5 border border-slate-800/80"
              >
                <div>
                  <div className="font-semibold text-slate-200">
                    {idx + 1}. {leg.homeTeam} vs {leg.awayTeam}
                  </div>
                  <div className="text-[11px] text-slate-400">
                    {leg.league} • Pick: <span className="text-cyan-300 font-medium">{leg.targetSelection || leg.selection}</span>
                  </div>
                </div>

                <div className="text-right">
                  <div className="font-mono font-bold text-emerald-400">
                    @{leg.odds.toFixed(2)}
                  </div>
                  <span className="text-[10px] font-mono text-slate-500">
                    {leg.riskLevel}
                  </span>
                </div>
              </div>
            ))}
          </div>
        </div>

        {/* Action Buttons */}
        <div className="mt-5 flex flex-col sm:flex-row items-center justify-between gap-3">
          {/* Copy WhatsApp / Telegram */}
          <button
            type="button"
            onClick={handleCopyChatFormat}
            className={`flex w-full sm:w-auto items-center justify-center gap-2 rounded-xl px-4 py-2.5 text-xs font-bold transition-all shadow-md cursor-pointer ${
              copiedText
                ? 'bg-emerald-500 text-slate-950'
                : 'bg-emerald-500/15 hover:bg-emerald-500/25 text-emerald-300 border border-emerald-500/30'
            }`}
          >
            {copiedText ? (
              <>
                <Check className="h-4 w-4 stroke-[3]" />
                <span>Copied for WhatsApp / Telegram!</span>
              </>
            ) : (
              <>
                <MessageCircle className="h-4 w-4" />
                <span>Copy for WhatsApp / Telegram</span>
              </>
            )}
          </button>

          {/* Download Image Button */}
          <button
            type="button"
            onClick={handleDownloadImage}
            disabled={isDownloading}
            className="flex w-full sm:w-auto items-center justify-center gap-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700 px-4 py-2.5 text-xs font-semibold transition-all cursor-pointer"
          >
            <Download className="h-4 w-4" />
            <span>{isDownloading ? 'Generating Image...' : 'Download Slip Image'}</span>
          </button>
        </div>
      </div>
    </div>
  );
};

